@dataclass(slots=True)
class SourceDoc:
    idx: int
    outlet: str
    kind: str  # media | telegram
    url: str | None
    published_at: datetime
    date_confidence: str
    title: str
    text: str
    fwd_from: str | None = None
    day_only: bool = False  # известен только день выхода (дата из URL или шапки статьи)


def _xml_attr(v: str) -> str:
    return v.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def _xml_text(v: str) -> str:
    return v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_user_prompt(
    docs: list[SourceDoc],
    now: datetime,
    audience_tz: str,
    scene_hint: str,
    mode: str = "standard",
    previous: dict | None = None,
) -> str:
    tz = ZoneInfo(audience_tz)
    lines = [
        f"Текущее время: {now.astimezone(tz):%Y-%m-%d %H:%M} ({audience_tz}), {now:%Y-%m-%dT%H:%MZ} UTC.",
        f"Сцена по источникам: {scene_hint}. Источников: {len(docs)}.",
        "",
    ]
    for d in docs:
        if d.day_only:  # условное время дня не выдаём за точное — иначе модель его напишет
            pub = f"{d.published_at:%Y-%m-%d} (известна только дата, время не указано)"
        else:
            pub = f"{d.published_at:%Y-%m-%dT%H:%MZ} UTC / {d.published_at.astimezone(tz):%d.%m %H:%M} {audience_tz}"
        attrs = (
            f'id="{d.idx}" outlet="{_xml_attr(d.outlet)}" type="{d.kind}" published="{pub}" '
            f'date_confidence="{d.date_confidence}"'
        )
        if d.url:
            attrs += f' url="{_xml_attr(d.url)}"'
        if d.fwd_from:
            attrs += f' repost_of="{_xml_attr(d.fwd_from)}"'
        lines.append(f"<source {attrs}>")
        lines.append(f"<title>{_xml_text(d.title)}</title>")
        lines.append(f"<text>{_xml_text(d.text)}</text>")
        lines.append("</source>")
        lines.append("")
    if previous:
        lines.append("<previous_draft>")
        lines.append(f"headline: {previous.get('headline', '')}")
        for b in previous.get("bullets", []):
            lines.append(f"- {b}")
        lines.append(f"summary: {previous.get('summary', '')}")
        lines.append("</previous_draft>")
        lines.append("")
    instr = MODE_INSTRUCTIONS.get(mode, "")
    if instr:
        lines.append(instr)
    lines.append("Собери пост по правилам редакции.")
    return "\n".join(lines)
